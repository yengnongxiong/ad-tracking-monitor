"""`report`: evals/message_match/results/report.md, generated from every results file.

Every number in it comes from a results file written by `run`; nothing is typed in by hand.
"""

import math
from pathlib import Path
from typing import Any

from tagmonitor.evals.metrics import SCALE
from tagmonitor.evals.run import EvalResult, load_results

REPORT_FILE = "report.md"
MAX_DISAGREEMENTS = 15


def _num(value: Any, digits: int = 2) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{value:.{digits}f}"


def _pct(value: Any) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    return f"{value:.0%}"


def _interval(pair: Any, fmt: Any) -> str:
    if not pair or any(v is None or math.isnan(v) for v in pair):
        return ""
    return f" ({fmt(pair[0])} to {fmt(pair[1])})"


def _cost(value: float | None) -> str:
    return "n/a" if value is None else f"${value:.4f}"


def _row(result: EvalResult) -> str:
    m = result.metrics or {}
    return (
        f"| {result.created_at:%Y-%m-%d %H:%M} | {result.prompt_version} | {result.model} | "
        f"{result.n_scored} | {_pct(m.get('exact'))}{_interval(m.get('exact_ci'), _pct)} | "
        f"{_pct(m.get('within_one'))} | "
        f"{_num(m.get('kappa'))}{_interval(m.get('kappa_ci'), _num)} | {_num(m.get('mae'))} | "
        f"{_num(m.get('mean_human'), 1)} / {_num(m.get('mean_model'), 1)} | "
        f"{result.n_errors} | {_cost(result.estimated_cost_usd)} |"
    )


TABLE_HEADER = [
    "| Run (UTC) | Prompt | Model | n | Exact (95% CI) | Within 1 | QWK (95% CI) | MAE "
    "| Mean human / model | Errors | Cost |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]


def render_report(results: list[EvalResult]) -> str:
    lines = [
        "# Message match: eval results",
        "",
        "> Generated by `python -m tagmonitor.evals report` from the results files in this "
        "folder; every number comes from a `run`. The model's overall score (1-5) is compared "
        "with human labels.",
        "",
    ]
    if not results:
        return "\n".join([*lines, "No runs yet.", ""])

    test_runs = [r for r in results if r.split == "test"]
    dev_runs = [r for r in results if r.split == "dev"]
    lines += ["## Test split (held out)", ""]
    if test_runs:
        if len(test_runs) > 1:
            lines += [
                f"**The test split was scored {len(test_runs)} times.** Only the first run "
                "is a clean held-out number; later ones may reflect tuning against test.",
                "",
            ]
        lines += [*TABLE_HEADER, *(_row(r) for r in test_runs), ""]
    else:
        lines += ["Not scored yet. Tune on dev, then score test once with the final prompt.", ""]

    lines += ["## Dev split: prompt versions compared", ""]
    if dev_runs:
        lines += [*TABLE_HEADER, *(_row(r) for r in dev_runs), ""]
    else:
        lines += ["No dev runs yet.", ""]

    latest = results[-1]
    lines += _details(latest)
    lines += [
        "## How to read this",
        "",
        "- **Exact / within 1:** the share of examples where the model's overall score equals "
        "the human's, or is at most one point off. 95% Wilson intervals.",
        "- **QWK:** Cohen's kappa with quadratic weights, on the fixed 1-5 scale. 1 is perfect "
        "agreement and 0 is what chance would give with the same score distributions; a "
        "two-point miss costs four times a one-point miss. The interval is a seeded 95% "
        "bootstrap. With a few dozen examples these intervals are wide, and that's the honest "
        "picture.",
        "- **MAE:** the mean absolute difference in points. **Mean human / model** shows "
        "whether the model is systematically harsher or kinder than the labeler.",
        "- **Errors:** examples with no usable answer (API errors, the daily limit, invalid "
        "output); they are left out of the metrics, so check them.",
        "- **Cost:** what all the answers cost at list prices, including answers served "
        "from the cache (llm/pricing.py).",
        "",
    ]
    return "\n".join(lines)


def _details(result: EvalResult) -> list[str]:
    lines = [
        f"## Latest run: prompt {result.prompt_version} on {result.split}",
        "",
        f"{result.created_at:%Y-%m-%d %H:%M} UTC, model `{result.model}`, "
        f"prompt sha256 `{result.prompt_sha256[:12]}`. {result.n_labeled} labeled examples, "
        f"{result.n_scored} scored, {result.n_errors} errors"
        + (f", {result.stale_labels} stale labels skipped" if result.stale_labels else "")
        + ".",
        "",
    ]
    if result.metrics:
        confusion = result.metrics["confusion"]
        assert isinstance(confusion, list)
        lines += [
            "Confusion matrix (rows: human, columns: model):",
            "",
            "| human \\ model | " + " | ".join(str(s) for s in SCALE) + " |",
            "|---|" + "---|" * len(SCALE),
            *(
                f"| **{score}** | " + " | ".join(str(n) for n in row) + " |"
                for score, row in zip(SCALE, confusion, strict=True)
            ),
            "",
        ]
    misses = sorted(
        (e for e in result.examples if e.model is not None and e.model != e.human),
        key=lambda e: (-abs((e.model or 0) - e.human), e.example_id),
    )[:MAX_DISAGREEMENTS]
    if misses:
        lines += [
            "Largest disagreements:",
            "",
            "| Example | Human | Model | Model's first issue | Labeler's note |",
            "|---|---|---|---|---|",
        ]
        for e in misses:
            issue = e.issues[0] if e.issues else ""
            lines.append(
                f"| `{e.example_id}` | {e.human} | {e.model} | {_cell(issue)} | "
                f"{_cell(e.human_notes)} |"
            )
        lines.append("")
    errors = [e for e in result.examples if e.model is None]
    if errors:
        lines += ["Errors:", ""]
        lines += [f"- `{e.example_id}`: {_cell(e.error or '')}" for e in errors]
        lines.append("")
    return lines


def _cell(text: str, limit: int = 160) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def write_report(results_dir: Path) -> Path:
    path = results_dir / REPORT_FILE
    path.write_text(render_report(load_results(results_dir)))
    return path
